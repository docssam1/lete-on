const makeProblem = (id, level, heights) => {
  const depth = heights.length;
  const width = heights[0].length;
  return {
    id,
    level,
    board: [width, depth],
    maxHeight: Math.max(...heights.flat()),
    heights,
    answer: { total: heights.flat().reduce((sum, value) => sum + value, 0) }
  };
};

