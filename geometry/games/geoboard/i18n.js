/* =========================================================================
   점판 공작소 (Geoboard Studio) — every user-facing string, in ko / zh / ja / en.

   WHY one file: the engine never holds a literal sentence, so a translator (or a
   reviewer checking key parity) reads only this file, and .selftest.mjs can prove
   all four languages carry exactly the same key set.

   WHY the success words live in `common`: `GOOD JOB!` / `GREAT JOB!` / `SUCCESS!`
   are shown identically in every language across Geometry World, so they must not
   be able to drift apart between locales.

   WHY there are six different wrong-action messages: the design document asks that
   자기 교차, 격친 선, 중복 꿁짓점 be reported IMMEDIATELY and by name. Each message
   says WHICH RULE the tap broke and nothing about where the answer is — a wrong
   action never gets praise audio and never gets a hint.
   ========================================================================= */

