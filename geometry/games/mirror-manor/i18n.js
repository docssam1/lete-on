export const LANGUAGES = ["ko", "zh", "ja", "en"];

/** Look up a string, falling back to Korean (the authoring language) then the key. */
export function text(lang, key, vars) {
  const source = messages[lang]?.[key] ?? messages.ko[key] ?? key;
  if (!vars) return source;
  return Object.entries(vars).reduce((line, [name, value]) => line.replaceAll(`{${name}}`, value), source);
}
