"use strict";

const assert = require("node:assert/strict");
global.window = {};
require("./source-inventory-4-1.js");
require("./source-inventory-grade6.js");
require("./curriculum.js");
require("./generators.js");
const source = require("./source-5-2-cuboid-page55-mission4.js");
const type = window.HSE_CURRICULUM.semesters.find(x => x.id === "5-2")?.units.find(x => x.id === "5-2-u5")?.subunits.find(x => x.name === "주사위에 관한 문제 ①")?.types.find(x => x.sourceItemId === source.definition.sourceItemId);
assert(type, "source type exists in the dice-arrangement subunit");
assert.equal(type.reviewLocked, false, "source is unlocked after responsive and A4 review");
assert.equal(type.generationMode, "fixed-verified-pool");
assert.equal(type.verifiedVariantCount, 1);
assert.equal(window.HSE_GENERATORS.generatorKey(type), source.definition.generatorKey, "verified source uses its dedicated generator");
const model = source.verifyModel();
assert.deepEqual(model.visibleFaces, [1, 3, 5, 1, 2, 3, 6, 2, 4]);
assert.equal(model.visibleFaceCount, 9);
assert.equal(model.visiblePips, 27);
assert.equal(model.allPips, 84);
assert.equal(model.answer, 57);
const generated = source.makeQuestion();
assert.equal(generated.answer, "57");
assert.equal(generated.publisherAnswerVerified, false);
assert.equal(generated.handwrittenAnswerVerified, false);
assert.equal(generated.sourceStructurePreserved, true);
assert.match(generated.prompt, /네 개의 주사위/);
assert.doesNotMatch(generated.prompt, /답: 57|data-source-answer/);
assert.doesNotMatch(generated.prompt, /source52-p55m4-answer-line/, "worksheet provides the answer area");
assert.equal((generated.prompt.match(/class="source52-p55m4-die"/g) || []).length, 3, "three visible dice and one fully occluded die are modeled");
assert.equal((generated.prompt.match(/class="source52-p55m4-pip"/g) || []).length, 27, "all 27 printed pips are drawn");
assert.match(generated.solution, /21×4=84/);
assert.match(generated.solution, /84−27=57/);
const runtimeQuestion = window.HSE_GENERATORS.generate(type, 2, 0, 54, 0);
assert.equal(runtimeQuestion.answer, "57", "unlocked runtime generates the fixed source question");
assert.equal(window.HSE_GENERATORS.generate(type, 2, 0, 54, 1), null, "unverified variants stay unavailable");
console.log(JSON.stringify({ status: "passed", sourceItemId: source.definition.sourceItemId, answer: generated.answer, visiblePips: model.visiblePips, hiddenDieCount: 1, reviewLocked: false }));
