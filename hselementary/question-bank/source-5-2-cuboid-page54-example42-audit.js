"use strict";
const assert = require("node:assert/strict");
const source = require("./source-5-2-cuboid-page54-example42.js");
const model = source.verifyModel();
assert.equal(source.rotations.length, 24);
assert.equal(model.modelCount, 24);
assert.deepEqual(model.oppositePairs.map(pair => [...pair]), [["A", "B"], ["C", "E"], ["D", "F"]]);
assert.deepEqual([...model.answers], ["B", "F", "C"]);
const item = source.makeQuestion();
assert.equal(item.answer, "A→B, D→F, E→C");
assert.equal(item.answerModel.modelCount, 24);
assert.equal((item.prompt.match(/<figure>/g) || []).length, 3);
assert.match(item.solution, /답: B, F, C/);
assert.match(item.solution, /둘째와 셋째 그림에서 B는 모두 오른쪽 면/);
assert.match(item.solution, /남은 두 면은 C와 E/);
const type = { id: source.definition.sourceItemId, sourceItemId: source.definition.sourceItemId, generatorKey: source.definition.generatorKey, sourceVerified: true, reviewLocked: false };
const api = { names: [], generatorKey: () => "legacy", generate: () => null };
source.install({ HSE_GENERATORS: api });
assert.equal(api.generatorKey(type), source.definition.generatorKey);
assert.equal(api.generate(type, 0, 0, 0, 0).answer, item.answer);
assert.equal(api.generate(type, 0, 0, 0, 1), null);
assert.equal(api.generate({ ...type, reviewLocked: true }, 0, 0, 0, 0), null);
assert.equal(api.generate({ ...type, sourceVerified: false }, 0, 0, 0, 0), null);
console.log("5-2 U5 p.54 Example 4-2 source views, 24 proper rotations, unique opposite pairs, fixed pool, and lock audit passed.");
