"use strict";

const assert = require("node:assert/strict");
global.window = {};
require("./source-inventory-4-1.js");
require("./source-inventory-grade6.js");
require("./curriculum.js");
require("./generators.js");
const source = require("./source-5-2-cuboid-page55-mission2.js");
const type = window.HSE_CURRICULUM.semesters.find(x => x.id === "5-2")?.units.find(x => x.id === "5-2-u5")?.subunits.find(x => x.name === "주사위에 관한 문제 ①")?.types.find(x => x.sourceItemId === source.definition.sourceItemId);
assert(type, "source type exists in the dice-arrangement subunit");
assert.equal(type.reviewLocked, false, "source is unlocked after responsive and A4 review");
assert.equal(type.generationMode, "fixed-verified-pool");
assert.equal(type.verifiedVariantCount, 1);
assert.equal(window.HSE_GENERATORS.generatorKey(type), source.definition.generatorKey, "verified source uses its dedicated generator");
const model = source.verifyModel();
assert.deepEqual(model.observedViews, [["라", "나", "바"], ["다", "라", "마"], ["가", "나", "다"]]);
assert.deepEqual(model.faceAssignment, { top: "라", bottom: "가", front: "나", back: "마", right: "바", left: "다" });
assert.deepEqual(model.answers, { 가: "라", 나: "마", 다: "바" });
assert.equal(model.properCubeRotations, 24);
assert.equal(model.consistentAssignments, 1);
const generated = source.makeQuestion();
assert.equal(generated.answer, "가→라, 나→마, 다→바");
assert.equal(generated.publisherAnswerVerified, false);
assert.equal(generated.handwrittenAnswerVerified, false);
assert.equal(generated.sourceStructurePreserved, true);
assert.match(generated.prompt, /세 방향에서 본 그림/);
assert.doesNotMatch(generated.prompt, /가→라|나→마|다→바|data-source-answer/);
assert.equal((generated.prompt.match(/class="source52-p55m2-cube"/g) || []).length, 3);
assert.doesNotMatch(source.cubeSvg(source.views[0], 0), /M85 15v60/, "top face must not contain a spurious dividing line");
assert.match(generated.solution, /나와 이웃한 면은 라, 바, 가, 다/);
assert.match(generated.solution, /라와 이웃한 면은 나, 바, 다, 마/);
assert.match(generated.solution, /가–라, 나–마, 다–바/);
assert.equal((generated.solution.match(/class="source52-p55m2-cube"/g) || []).length, 3, "solution-only print retains its three reference views");
const runtimeQuestion = window.HSE_GENERATORS.generate(type, 2, 0, 52, 0);
assert.equal(runtimeQuestion.answer, "가→라, 나→마, 다→바", "unlocked runtime generates the fixed source question");
assert.equal(window.HSE_GENERATORS.generate(type, 2, 0, 52, 1), null, "unverified variants stay unavailable");
console.log(JSON.stringify({ status: "passed", sourceItemId: source.definition.sourceItemId, answers: generated.answer, properCubeRotations: 24, uniqueAssignments: 1, reviewLocked: false }));
