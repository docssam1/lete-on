"use strict";
const assert = require("node:assert/strict");
const api = require("./source-5-2-cuboid-page53-mission5.js");
const item = api.build();
assert.deepEqual(api.views, [[['나',-90],['가',-90],['바',0]],[['라',-90],['마',0],['다',-90]],[['나',90],['다',90],['마',180]]]);
