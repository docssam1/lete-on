const independentlyFormat = (num, den) => {
  let a=num,b=den;while(b)[a,b]=[b,a%b];num/=a;den/=a;
  const whole=Math.floor(num/den), remainder=num%den;
  return remainder ? `${whole ? `${whole} ` : ""}${remainder}/${den}` : String(whole);
};
