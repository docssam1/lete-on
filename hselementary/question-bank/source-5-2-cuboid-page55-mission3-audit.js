"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
global.window = {};
require("./source-inventory-4-1.js");
require("./source-inventory-grade6.js");
require("./curriculum.js");
require("./generators.js");
const source = require("./source-5-2-cuboid-page55-mission3.js");
const type = window.HSE_CURRICULUM.semesters.find(x => x.id === "5-2")?.units.find(x => x.id === "5-2-u5")?.subunits.find(x => x.name === "주사위에 관한 문제 ①")?.types.find(x => x.sourceItemId === source.definition.sourceItemId);
assert(type, "source type exists in the dice-arrangement subunit");
assert.equal(type.reviewLocked, false, "source is unlocked after responsive and A4 review");
assert.equal(type.generationMode, "fixed-verified-pool");
assert.equal(type.verifiedVariantCount, 1);
assert.equal(window.HSE_GENERATORS.generatorKey(type), source.definition.generatorKey, "verified source uses its dedicated generator");
const model = source.verifyModel();
assert.deepEqual(model.oppositePairs, [[1, 3], [2, 5], [4, 6]]);
assert.deepEqual(model.frontFaces, [2, null, 3, 4, 6, 3]);
assert.equal(model.knownBackSum, 17);
assert.equal(model.missingBackValue, 5);
assert.equal(model.answer, 2);
const generated = source.makeQuestion();
assert.equal(generated.answer, "2");
assert.equal(generated.publisherAnswerVerified, false);
assert.equal(generated.handwrittenAnswerVerified, false);
assert.equal(generated.sourceStructurePreserved, true);
assert.match(generated.prompt, /뒤쪽 면에 적힌 수들의 합이 22/);
assert.doesNotMatch(generated.prompt, /답: 2|data-source-answer/);
assert.doesNotMatch(generated.prompt, /source52-p55m3-answer-line/, "worksheet supplies the single answer area");
assert.equal((generated.prompt.match(/data-net-face=/g) || []).length, 6);
assert.equal((generated.prompt.match(/class="source52-p55m3-cube"/g) || []).length, 6);
assert.match(generated.prompt, /똑같은 정육면체 6개/);
for (const compact of [false, true]) {
  const stack = source.stackSvg({ compact });
  const fronts = [...stack.matchAll(/class="source52-p55m3-front-face" x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"/g)].map(m => ({ x: +m[1], y: +m[2], size: +m[3] }));
  assert.equal(fronts.length, 6);
  assert.equal(fronts[3].y + fronts[3].size, fronts[0].y, "middle layer rests on bottom layer");
  assert.equal(fronts[4].y + fronts[4].size, fronts[1].y, "both middle cubes touch bottom layer");
  assert.equal(fronts[5].y + fronts[5].size, fronts[3].y, "top layer rests on middle layer");
}
assert.match(generated.solution, /5\+1\+6\+4\+1=17/);
assert.match(generated.solution, /22−17=5/);
assert.match(generated.solution, /답: 2/);
assert.match(source.stackSvg(), /aria-label="[^"]*2, ㉠, 3/);
assert.match(source.stackSvg({ solution: true }), /aria-label="[^"]*2, 2, 3/);
const runtimeQuestion = window.HSE_GENERATORS.generate(type, 2, 0, 53, 0);
assert.equal(runtimeQuestion.answer, "2", "unlocked runtime generates the fixed source question");
assert.equal(window.HSE_GENERATORS.generate(type, 2, 0, 53, 1), null, "unverified variants stay unavailable");
const review = JSON.parse(fs.readFileSync(path.join(__dirname, "source-inventory/5-2-u5-readiness-review.json"), "utf8")).items.find(row => row.sourceItemId === source.definition.sourceItemId);
assert.match(review.originalStructure, /정육면체 6개/);
assert.doesNotMatch(review.originalStructure, /직육면체/);
console.log(JSON.stringify({ status: "passed", sourceItemId: source.definition.sourceItemId, answer: generated.answer, oppositePairs: model.oppositePairs, knownBackSum: model.knownBackSum, reviewLocked: false }));
