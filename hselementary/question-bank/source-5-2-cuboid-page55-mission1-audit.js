"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
global.window = {};
require("./source-inventory-4-1.js");
require("./source-inventory-grade6.js");
require("./curriculum.js");
require("./generators.js");
const source = require("./source-5-2-cuboid-page55-mission1.js");
const type = window.HSE_CURRICULUM.semesters.find(x => x.id === "5-2")?.units.find(x => x.id === "5-2-u5")?.subunits.find(x => x.name === "주사위에 관한 문제 ①")?.types.find(x => x.sourceItemId === source.definition.sourceItemId);
assert(type, "source type exists in dice-arrangement subunit");
assert.equal(type.reviewLocked, false, "source is unlocked after screen and A4 review");
assert.equal(type.generationMode, "fixed-verified-pool");
assert.equal(type.verifiedVariantCount, 1);
assert.equal(window.HSE_GENERATORS.generatorKey(type), source.definition.generatorKey, "verified source uses its dedicated generator");
const model = source.verifyModel();
assert.deepEqual(model.reverseSteps.map(x => x.value), [5, 3, 4, 4]);
assert.equal(model.answer, 4);
const generated = source.makeQuestion();
assert.equal(generated.answer, "4");
assert.equal(generated.publisherAnswerVerified, false);
assert.equal(generated.handwrittenAnswerVerified, false);
assert.equal(generated.sourceStructurePreserved, true);
assert.match(generated.prompt, /마주 보는 면에 쓰인 두 수의 합은 모두 7/);
assert.match(generated.prompt, /마주 붙인 면의 두 수의 합은 모두 8/);
assert.equal(generated.prompt.match(/data-source-item-id=/g)?.length, 1);
assert.doesNotMatch(generated.prompt, /답: 4|data-source-answer/, "answer remains out of problem prompt");
assert.equal((generated.prompt.match(/source52-p55m1-top/g) || []).length, 5, "diagram shows all five top faces");
assert.equal((generated.prompt.match(/source52-p55m1-front/g) || []).length, 3, "diagram shows the three exposed front faces");
assert.equal((generated.prompt.match(/source52-p55m1-right/g) || []).length, 3, "diagram shows the three exposed right faces");
assert.match(generated.solution, /오른쪽 끝 바깥 면이 2/);
assert.match(generated.solution, /붙은 면은 6/);
assert.match(generated.solution, /답: 4/);
assert.doesNotMatch(generated.solution, /source52-p55m1-contact-labels/, "hidden contact values must not appear on visible faces");
assert.match(generated.solution, /맞닿은 면은 그림 안쪽에 가려져 있습니다/);
const runtimeQuestion = window.HSE_GENERATORS.generate(type, 2, 0, 51, 0);
assert.equal(runtimeQuestion.answer, "4", "unlocked runtime generates the verified source question");
assert.equal(window.HSE_GENERATORS.generate(type, 2, 0, 51, 1), null, "unverified variant remains unavailable");
const review = JSON.parse(fs.readFileSync(path.join(__dirname, "source-inventory/5-2-u5-readiness-review.json"), "utf8")).items.find(row => row.sourceItemId === source.definition.sourceItemId);
assert.match(review.originalStructure, /꺾이는 주사위의 윗면은 2/);
assert.doesNotMatch(review.originalStructure, /한쪽 끝 주사위의 윗면은 2/);
console.log(JSON.stringify({ status: "passed", sourceItemId: source.definition.sourceItemId, sourceAnswer: generated.answer, verifiedVariants: 1, reviewLocked: false }));
