'use strict';
const assert = require('node:assert/strict');
global.window = {};
require('./source-inventory-4-1.js');
require('./source-inventory-grade6.js');
require('./curriculum.js');
require('./generators.js');
const item = require('./source-5-2-cuboid-page52-example34.js');
const type = window.HSE_CURRICULUM.semesters.flatMap(s=>s.units.flatMap(u=>u.subunits.flatMap(g=>g.types))).find(t=>t.id===item.sourceItemId);
assert(type && type.sourceVerified && !type.reviewLocked);
assert.equal(type.publisherKeyVerified,false);
assert.deepEqual(item.cells, [[0,0],[1,0],[1,1],[2,1],[2,2],[3,2]]);
assert.deepEqual(item.marks, [[[0,1],[1,0]],[[0,.5],[1,.5]],[[.5,0],[.5,1]],[[0,0],[1,1]],[[0,.5],[1,.5]],[[0,1],[1,0]]]);
assert.deepEqual(item.choices, [['H','\\','\\'],['H','\\','/'],['\\','V','/'],['V','V','\\'],['\\','H','H']]);
const q=window.HSE_GENERATORS.generate(type,0,0,0,0);
assert.equal(q.answer,'②');
assert.equal(q.publisherKeyVerified,false);
assert.equal((q.prompt.match(/class="p52e34-cube"/g)||[]).length,5);
assert.doesNotMatch(q.prompt,/답:|대각선 두 개가 한 꼭짓점/);
assert.match(q.solution,/대각선 두 개가 한 꼭짓점에서 만날 수 없습니다/);
assert.equal(window.HSE_GENERATORS.generate(type,0,0,0,1),null);
assert.equal(window.HSE_GENERATORS.generate({...type,reviewLocked:true},0,0,0,0),null);
assert.equal(window.HSE_GENERATORS.generate({...type,sourceVerified:false},0,0,0,0),null);
console.log('PASS: exact net, five source choices, answer separation, one verified item, and lock guards.');
