"use strict";

const assert = require("node:assert/strict");
const inventory = require("./source-inventory/5-2-source-items.json");
const readiness = require("./source-inventory/5-2-u5-readiness-review.json");
global.window = {};
require("./source-inventory-4-1.js");
require("./source-inventory-grade6.js");
require("./curriculum.js");
require("./generators.js");
const source = require("./source-5-2-cuboid-page49-mission3.js");
const itemId = source.definition.sourceItemId;
const type = window.HSE_CURRICULUM.semesters.find(x => x.id === "5-2")?.units.find(x => x.id === "5-2-u5")?.subunits.find(x => x.name === "직육면체의 성질")?.types.find(x => x.sourceItemId === itemId);
assert(type, "runtime type contains the source item");
assert.equal(inventory.sourceItems.find(x => x.sourceItemId === itemId)?.implementationStatus, "verified-local");
assert.equal(readiness.items.find(x => x.sourceItemId === itemId)?.publicDecision, "public");
assert.equal(type.reviewLocked, false);
assert.equal(type.sourceVerified, true);
assert.equal(window.HSE_GENERATORS.generatorKey(type), source.definition.generatorKey);

const model = source.verifyModel();
assert.deepEqual(model.loops.map(loop => loop.perimeterCm), [130, 118, 108]);
assert.equal(model.oneWrapCm, 356);
assert.equal(model.wrapsPerLoop, 2);
assert.equal(model.wrappedTapeCm, 712);
assert.equal(model.knotCount, 3);
assert.equal(model.knotTapeCm, 48);
assert.equal(model.totalCm, 760);
const generated = window.HSE_GENERATORS.generate(type, 2, 0, 49, 0);
assert(generated, "one fixed verified source variant generates");
assert.equal(window.HSE_GENERATORS.generate(type, 2, 0, 49, 1), null, "invented variants are rejected");
assert.equal(generated.answer, "760cm");
assert.equal(generated.publisherKeyVerified, false);
assert.equal(generated.handwrittenAnswerVerified, false);
assert((generated.prompt.match(/<path\b/g) || []).length >= 4, "cuboid, wraps, and dimension arrows are drawn as SVG paths");
assert.match(generated.prompt, /색 테이프는 2번씩 감았고/);
assert.match(generated.prompt, /매듭을 묶는 데 16cm씩/);
assert.equal((generated.prompt.match(/<g class="source52-p49m3-knot"/g) || []).length, 3, "question diagram shows the three source knots");
assert.match(generated.prompt, /data-loop-count="3" data-wraps-per-loop="2"/);
assert(!generated.prompt.includes("source52-p49m3-hidden"), "hidden rear edges do not cross the front face");
assert(generated.prompt.includes('M359 329 469 249'), "depth dimension follows the receding edge");
for (const path of ["M95 242H345L455 162M95 258H345L455 178", "M145 149H395V279M155 141H405V271", "M212 315V185L322 105M228 315V185L338 105"]) assert(generated.prompt.includes(path), "only visible tape segments are drawn");
assert.doesNotMatch(generated.prompt, /760cm|data-source-answer/, "answer stays out of the prompt");
for (const phrase of ["130cm", "118cm", "108cm", "712cm", "48cm", "760cm"]) assert(generated.solution.includes(phrase), `solution includes ${phrase}`);
assert.equal((generated.solution.match(/<g class="source52-p49m3-knot"/g) || []).length, 3);
console.log(JSON.stringify({ status: "passed", sourceItemId: itemId, loopPerimetersCm: model.loops.map(loop => loop.perimeterCm), twiceWrappedCm: model.wrappedTapeCm, knotCount: model.knotCount, knotTapeCm: model.knotTapeCm, answerCm: model.totalCm, fixedVariants: 1, publisherKeyVerified: false }));
