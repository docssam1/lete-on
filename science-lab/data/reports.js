// 실험 id → 설정(없으면 공통만). 가이드·질문은 공통(대회 × 수준) + 실험 것을 합친다.
// 결과 표: 그 대회용 표(tables[대회]) → 실험의 기본 대회면 table → 대회 × 수준 기본 표.
export const primaryContest = (unitId) => (CONTEST_OF[unitId] || ['inquiry'])[0];
export function reportCfg(unitId, level, contest) {
  const own = REPORTS[unitId] || {}, lv = level || own.level || 'elem', ct = COMMON[contest] ? contest : primaryContest(unitId);
  const base = (COMMON[ct] || INQUIRY)[lv] || INQUIRY.elem, mine = own.by?.[ct] || (ct === primaryContest(unitId) ? own : {});
  const merge = (k) => { const o = {}; for (const key of new Set([...Object.keys(base[k]), ...Object.keys(mine[k] || {})])) o[key] = [...(base[k][key] || []), ...(mine[k]?.[key] || [])]; return o; };
  const table = mine.table || FORM_TABLE[ct][lv];
  return { ...mine, by: undefined, level: lv, contest: ct, table, guide: merge('guide'), asks: merge('asks') };   // 다른 대회 양식에 기본 대회의 탐구 문제·표가 새지 않게 mine만
}
