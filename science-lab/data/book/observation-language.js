const maps=Object.fromEntries(Object.entries(edits).map(([u,pairs])=>[u,new Map(pairs)]));
const bodyMaps=Object.fromEntries(Object.entries(bodyEdits).map(([u,pairs])=>[u,new Map(pairs)]));
function replace(value,map){
 if(typeof value==='string')return map.get(value)??value;
 if(Array.isArray(value))return value.map(v=>replace(v,map));
 if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).map(([key,v])=>[key,replace(v,map)]));
 return value;
}
function presentation(q,unit,book){
 const map=maps[unit],next={...q};
 for(const key of book?['topic','prompt','choices','given','parts','options']:['prompt','choices','givens'])if(Object.hasOwn(q,key))next[key]=replace(q[key],map);
 if(!book&&q.taxonomy?.topic&&map.has(q.taxonomy.topic))next.taxonomy={...q.taxonomy,topic:map.get(q.taxonomy.topic)};
 return JSON.stringify(next)===JSON.stringify(q)?q:next;
}
const clone=value=>JSON.parse(JSON.stringify(value));
export function observationCurrentItems(rows,unit){
 if(!maps[unit]||!Array.isArray(rows))return rows;
 let changed=false;
 const current=rows.map(q=>{
  if(!q.id?.startsWith(unit+'-')||!/^[abt]\d+$/.test(q.id.slice(unit.length+1))||!['authored','authored-draft'].includes(q.status)||['original','similar'].includes(q.sourceRef?.type)||q.contentVersion===OBSERVATION_LANGUAGE_VERSION||q.previousVersions?.some(p=>p.version===OBSERVATION_LANGUAGE_VERSION))return q;
  const next=presentation(q,unit,false);if(next===q)return q;changed=true;
  return{...next,contentVersion:OBSERVATION_LANGUAGE_VERSION,previousVersions:[...(q.previousVersions?clone(q.previousVersions):[]),{...clone(q),version:q.contentVersion||1}]};
 });
 return changed?current:rows;
}
export function withObservationLanguage(workbook){
 if(!maps[workbook.unit])return workbook;
 const map=bodyMaps[workbook.unit],pages=rows=>map?rows?.map(p=>({...p,blocks:replace(p.blocks,map)})):rows;
 return{...workbook,questions:workbook.questions.map(q=>presentation(q,workbook.unit,true)),...(map?{pages:pages(workbook.pages),...(workbook.teacherStudentPages?{teacherStudentPages:pages(workbook.teacherStudentPages)}:{})}:{})};
}

