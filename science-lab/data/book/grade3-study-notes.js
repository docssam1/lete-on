function plantExample(page,index,unit){
 if(unit!=='s31-u03'||index!==4||page.section!==plant.section||page.title!==plant.title)return page;
 const example=page.blocks?.[1],field=page.blocks?.[2];
 if(example?.type!=='example'||field?.type!=='field')return page;
 const previous=[example.steps?.[2]?.[0],example.steps?.[2]?.[1],example.answer,field.title,field.hint];
 if(previous.some((text,i)=>text!==plant.previous[i]))return page;
 const steps=example.steps.map((row,i)=>i===2?[plant.current[0],plant.current[1]]:row);
 const blocks=page.blocks.map((block,i)=>i===1?{...block,steps,answer:plant.current[2]}:i===2?{...block,title:plant.current[3],hint:plant.current[4]}:block);
 return {...page,blocks};
}
export function withGrade3StudyNotes(workbook){
 if(!Object.hasOwn(notePatches,workbook?.unit))return workbook;
 const reviewed=notePatches[workbook.unit];let changed=false;const fields={};
 for(const key of ['pages','teacherStudentPages']){
  if(!Array.isArray(workbook[key]))continue;
  let pagesChanged=false;
  const pages=workbook[key].map((page,index)=>{
   let result=page;
   if(Array.isArray(page.rail)){
    let railChanged=false;
    const rail=page.rail.map(note=>{
     if(!Object.hasOwn(reviewed,note.title)||!Object.hasOwn(reviewed[note.title],note.text))return note;
     const text=reviewed[note.title]?.[note.text];
     if(typeof text!=='string'||text===note.text)return note;
     railChanged=true;return {...note,text};
    });
    if(railChanged)result={...result,rail};
   }
   result=plantExample(result,index,workbook.unit);
   if(result!==page)pagesChanged=true;
   return result;
  });
  if(pagesChanged){changed=true;fields[key]=pages;}
 }
 return changed?{...workbook,...fields}:workbook;
}
