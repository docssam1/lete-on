// 눈 결정(플러스 노트 작은 그림): 육각 대칭 가지
function flake() {
  const arm = (a) => { const r = (d) => `${(160 + Math.cos(a) * d).toFixed(1)},${(150 + Math.sin(a) * d).toFixed(1)}`, side = (d, s, l) => { const b = a + s * 0.6; return `M${r(d)} L${(160 + Math.cos(a) * d + Math.cos(b) * l).toFixed(1)},${(150 + Math.sin(a) * d + Math.sin(b) * l).toFixed(1)}`; };
    return `<path d="M160,150 L${r(110)} ${side(45, 1, 34)} ${side(45, -1, 34)} ${side(78, 1, 22)} ${side(78, -1, 22)}"/>`; };
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 300" role="img" aria-label="여섯 갈래로 뻗은 눈 결정"><rect width="320" height="300" rx="18" fill="#1d2a52"/>
    <g stroke="#eaf2ff" stroke-width="7" stroke-linecap="round" fill="none">${[0, 1, 2, 3, 4, 5].map((k) => arm(k * Math.PI / 3 - Math.PI / 2)).join('')}</g><circle cx="160" cy="150" r="12" fill="#eaf2ff"/></svg>`;
}
