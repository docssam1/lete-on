function reviseOpeningBody(workbook,unit,studentCount,teacherCount,edits){
 if(workbook.unit!==unit||workbook.pages.length!==studentCount||workbook.teacherStudentPages?.length!==teacherCount)throw Error('본문 언어 편집 대상과 쪽 수가 다릅니다.');
 const revise=(page,index)=>{
  const edit=edits[index+1];if(!edit)return page;
  const {from,blocks,...fields}=edit;
  if(page.title!==from)throw Error(`본문 ${index+1}쪽의 표제가 다릅니다.`);
  return {...page,...fields,blocks:page.blocks.map((block,i)=>{
   const patch=blocks?.[i];if(!patch)return block;
   if(block.type!==patch.type)throw Error(`본문 ${index+1}쪽 ${i}번 블록이 다릅니다.`);
   return {...block,...patch};
  })};
 };
 // Only the opening lesson pages are aligned. Leave all later split pages and
 // duplex blanks untouched; fail if a generator changes this shared prefix.
 for(const n of Object.keys(edits))if(JSON.stringify(workbook.teacherStudentPages[n-1])!==JSON.stringify(workbook.pages[n-1]))throw Error('학생/교사 공통 본문의 배치가 달라졌습니다.');
 return {...workbook,pages:workbook.pages.map(revise),teacherStudentPages:workbook.teacherStudentPages.map(revise)};
}

