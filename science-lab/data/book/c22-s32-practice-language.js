export const GRADE3_PRACTICE_UNITS=Object.freeze(Object.keys(patches));
const clone=value=>JSON.parse(JSON.stringify(value));
const cache=new WeakMap();

export function grade3PracticeCurrentItems(rows,unit){
 const bank=patches[unit]?.bank;
 if(!bank||!Array.isArray(rows))return rows;
 let changed=false;
 const next=rows.map(q=>{
  const patch=bank[q.id];
  if(!patch||q.status!=='authored'||!['authored-supplement','authored-lesson'].includes(q.sourceRef?.type)||(q.contentVersion||1)!==patch.previousVersion||q.prompt!==patch.previous)return q;
  changed=true;
  if(cache.has(q))return cache.get(q);
  const current={...q,prompt:patch.prompt,contentVersion:GRADE3_PRACTICE_LANGUAGE_VERSION,previousVersions:[...(q.previousVersions?clone(q.previousVersions):[]),{...clone(q),version:q.contentVersion||1}]};
  cache.set(q,current);return current;
 });
 return changed?next:rows;
}

export function withGrade3PracticeWorkbook(workbook){
 const reviewed=patches[workbook.unit]?.workbook;
 if(!reviewed)return workbook;
 let changed=false;
 const questions=workbook.questions.map(q=>{
  const patch=reviewed[q.no];
  if(!patch||q.prompt!==patch.previous)return q;
  changed=true;return {...q,prompt:patch.prompt};
 });
 return changed?{...workbook,questions}:workbook;
}

export function withGrade3PracticeClassroom(unit,mod){
 const items=grade3PracticeCurrentItems(mod.classroomItems,unit);
 return items===mod.classroomItems?mod:{...mod,classroomItems:items};
}
