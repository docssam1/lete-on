  changed=true;
  if(cache.has(q))return cache.get(q);
  const current={...q,prompt:patch.prompt,contentVersion:MAGNET_ELEMENTARY_VERSION,previousVersions:[...(q.previousVersions?clone(q.previousVersions):[]),{...clone(q),version:q.contentVersion||1}]};
