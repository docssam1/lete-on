export function withSolutionBodyLanguage(workbook){
 if(workbook.unit!=='c22-s51-u03'||workbook.pages.length!==75)throw Error('용해와 용액 본문 편집 대상이 다릅니다.');
 const revise=(page,index)=>{
  const edit=edits[index+1];if(!edit)return page;
  const {from,blocks,...fields}=edit;
  if(page.title!==from)throw Error(`용해 본문 ${index+1}쪽의 표제가 다릅니다.`);
  return {...page,...fields,blocks:page.blocks.map((block,i)=>{
   const patch=blocks?.[i];if(!patch)return block;
   if(block.type!==patch.type)throw Error(`용해 본문 ${index+1}쪽 ${i}번 블록이 다릅니다.`);
   return {...block,...patch};
  })};
 };
 if(workbook.teacherStudentPages&&workbook.teacherStudentPages.length!==75)throw Error('용해 교사용 본문의 쪽 수가 다릅니다.');
 return {...workbook,pages:workbook.pages.map(revise),...(workbook.teacherStudentPages?{teacherStudentPages:workbook.teacherStudentPages.map(revise)}:{})};
}
