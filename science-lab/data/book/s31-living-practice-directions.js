export function withGrade3LivingPracticeDirections(workbook){
 const reviewed=patches[workbook?.unit];
 if(!reviewed||!Array.isArray(workbook.questions))return workbook;
 let changed=false;
 const questions=workbook.questions.map(q=>{
  const patch=reviewed[q.no];
  if(!patch||q.no<41||q.no>80||q.id!==workbook.unit+'-w'+String(q.no).padStart(3,'0')||q.sourceId||q.sourceRef||q.contentVersion!=null||q.prompt!==patch.previous)return q;
  changed=true;return {...q,prompt:patch.prompt};
 });
 return changed?{...workbook,questions}:workbook;
}
