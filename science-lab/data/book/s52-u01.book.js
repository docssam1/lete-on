// 결과 막대그래프(인쇄용): 넣은 것별 평균 시간 + 값 이름표 + 축 이름(가로 = 넣은 것, 세로 = 평균 시간)
export const MEANS = ADDS.map((a) => bubbleModel(a).mean);
function graph() {
  const W = 640, H = 380, L = 70, Rt = 600, T = 54, B = 300, Y = (v) => B - (v / 70) * (B - T), names = ['그냥 비눗물', '설탕', '글리세린'];
  const C = '#3346a0', INK = '#1f2a44', MUTED = '#5b6577', GRID = '#e3e7ef', step = (Rt - L) / 3, bw = 92;
  const grid = [0, 20, 40, 60].map((v) => `<line x1="${L}" x2="${Rt}" y1="${Y(v)}" y2="${Y(v)}" stroke="${GRID}"/><text x="${L - 10}" y="${Y(v) + 5}" font-size="16" fill="${MUTED}" text-anchor="end">${v}</text>`).join('');
  const bars = MEANS.map((v, i) => { const x = L + step * i + (step - bw) / 2, y = Y(v);
    return `<rect x="${x}" y="${y}" width="${bw}" height="${B - y}" rx="5" fill="${C}"/><text x="${x + bw / 2}" y="${y - 9}" font-size="18" font-weight="800" fill="${INK}" text-anchor="middle">${v}초</text>
      <text x="${x + bw / 2}" y="${B + 24}" font-size="17" font-weight="700" fill="${INK}" text-anchor="middle">${names[i]}</text>`; }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" role="img" aria-label="넣은 것에 따른 비눗방울의 평균 시간 막대그래프: 그냥 비눗물 10초, 설탕 25초, 글리세린 59초" font-family="Pretendard, sans-serif">
    <rect width="${W}" height="${H}" rx="16" fill="#fff"/>${grid}<line x1="${L}" x2="${Rt}" y1="${B}" y2="${B}" stroke="#9aa3b2" stroke-width="1.4"/>${bars}
    <text x="16" y="28" font-size="17" font-weight="700" fill="${INK}">세로축: 평균 시간(초)</text>
    <text x="${(L + Rt) / 2}" y="${H - 14}" font-size="17" font-weight="700" fill="${INK}" text-anchor="middle">가로축: 넣은 것 · 세 번 잰 평균</text></svg>`;
}
// 세 방울이 120°로 만나는 그림 + 벌집(정육각형)
function cells() {
  const hex = (cx, cy, r) => Array.from({ length: 6 }, (_, k) => { const a = Math.PI / 6 + k * Math.PI / 3; return `${(cx + Math.cos(a) * r).toFixed(1)},${(cy + Math.sin(a) * r).toFixed(1)}`; }).join(' ');
  const comb = [];
  for (let row = 0; row < 3; row++) for (let col = 0; col < 4; col++) { const r = 34, cx = 420 + col * r * 1.732 + (row % 2) * r * 0.866, cy = 92 + row * r * 1.5; comb.push(`<polygon points="${hex(cx, cy, r)}" fill="#fff4d6" stroke="#c98a1a" stroke-width="3"/>`); }
  const cx = 160, cy = 150, R = 74, arms = [90, 210, 330].map((d) => { const a = d * Math.PI / 180; return [cx + Math.cos(a) * 90, cy - Math.sin(a) * 90]; });
  const circles = [30, 150, 270].map((d) => { const a = d * Math.PI / 180; return `<circle cx="${(cx + Math.cos(a) * 62).toFixed(1)}" cy="${(cy - Math.sin(a) * 62).toFixed(1)}" r="${R}" fill="#e6f1fb" fill-opacity=".55" stroke="#3346a0" stroke-width="2.5"/>`; }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 760 300" role="img" aria-label="세 비눗방울의 벽이 120도로 만나는 그림과 벌집의 정육각형" font-family="Pretendard, sans-serif">
    <rect width="760" height="300" rx="18" fill="#f6f3ec"/>${circles}
    ${arms.map(([x, y]) => `<line x1="${cx}" y1="${cy}" x2="${x.toFixed(1)}" y2="${y.toFixed(1)}" stroke="#c2581c" stroke-width="4"/>`).join('')}
    <path d="M${cx + 22} ${cy - 13} A26 26 0 0 0 ${cx} ${cy - 26}" fill="none" stroke="#1f2a44" stroke-width="2"/><text x="${cx + 26}" y="${cy - 26}" font-size="18" font-weight="800" fill="#1f2a44">120°</text>
    <text x="160" y="282" font-size="18" font-weight="800" fill="#1f2a44" text-anchor="middle">세 방울의 벽은 120°로 만나요</text>
    ${comb.join('')}<text x="560" y="282" font-size="18" font-weight="800" fill="#1f2a44" text-anchor="middle">벌집도 같은 각(정육각형)</text></svg>`;
}
