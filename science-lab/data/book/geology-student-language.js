function language(value){
 if(typeof value==='string')return phrases.reduce((text,[old,next])=>text.replaceAll(old,next),value);
 if(Array.isArray(value))return value.map(language);
 if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).map(([key,v])=>[key,language(v)]));
 return value;
}
function presentation(q,book){
 const next={...q,prompt:language(prompts[q.prompt]||q.prompt)};
 if(book&&topics[q.topic])next.topic=topics[q.topic];
 if(!book&&topics[q.taxonomy?.topic])next.taxonomy={...q.taxonomy,topic:topics[q.taxonomy.topic]};
 for(const key of book?['choices','given','parts']:['choices','givens'])if(Object.hasOwn(q,key))next[key]=language(q[key]);
 return JSON.stringify(next)===JSON.stringify(q)?q:next;
}
