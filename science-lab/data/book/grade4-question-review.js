export function grade4QuestionReview(rows,unit){
 if(unit==='c22-s42-u01')return skyResponseItems(rows,unit);
 if(!GRADE4_REVIEW_UNITS.includes(unit)||!Array.isArray(rows))return rows;
 let changed=false;
 const next=rows.map(q=>{
  const p=patches[q.id];
  if(!p||p.unit!==unit||q.status!=='authored'||q.sourceContent||q.contentVersion!==p.previousVersion||q.prompt!==p.prompt||!Object.keys(p.presentation).every(k=>same(q[k]??null,p.presentation[k]))||!same(q.sourceRef,p.sourceRef)||!same(q.taxonomy,p.taxonomy)||q.responseContract!==p.responseContract||!same(q.answerContract,p.previousAnswerContract)||p.previousChoices&&!same(q.choices,p.previousChoices))return q;
  changed=true;
  if(cache.has(q))return cache.get(q);
  const fields=p.choices?{choices:[...p.choices]}:{answerContract:clone(p.answerContract)};
  const current={...q,...fields,contentVersion:GRADE4_REVIEW_VERSION,previousVersions:[...(q.previousVersions?clone(q.previousVersions):[]),{...clone(q),version:q.contentVersion,snapshotKind:'full-question'}]};
  cache.set(q,current);return current;
 });
 return ecologyMaterialItems(biologyExampleItems(changed?next:rows,unit),unit);
}
export function withGrade4ReviewedWorkbook(workbook){
 if(!workbookUnits.has(workbook?.unit)||!Array.isArray(workbook.questions))return workbook;
 let changed=false;
 const questions=workbook.questions.map(q=>{
  const p=workbookPatches[q.id];
  if(!p||p.unit!==workbook.unit||q.contentVersion!=null||q.sourceContent||(q.status!=null&&q.status!=='authored')||q.prompt!==p.prompt||q.sourceId!==p.sourceId||!same(q.sourceRef,p.sourceRef)||!Object.entries(p.fields).every(([key,[previous]])=>same(q[key],previous)))return q;
  changed=true;return {...q,...Object.fromEntries(Object.entries(p.fields).map(([key,[,value]])=>[key,clone(value)]))};
 });
 return changed?{...workbook,questions}:workbook;
}
