const S = (w, h, body) => `<svg viewBox="0 0 ${w} ${h}" xmlns="http://www.w3.org/2000/svg" role="img" font-family="Pretendard, 'Noto Sans KR', sans-serif">${body}</svg>`;
const WATER = '#8cc8ec', ICE = '#dcf0fb', GLASS = '#6f86a0', RED = '#E23B2E', BLUE = '#1f6fd1', INK = '#1E3A78', GRAY = '#5B6577';

// 시험관: x(왼쪽), top(입구), bot(바닥 끝), lv(물·얼음 기둥 높이), ice(얼음이면 윗면이 살짝 볼록)
const TUBE = (x, top, bot, lv, { ice = false, marks = [] } = {}) => {
  const w = 32, r = 16, y = bot - lv;
  const liquid = ice
    ? `<path d="M${x + 2} ${y + 2} Q${x + w / 2} ${y - 3} ${x + w - 2} ${y + 2} V${bot - r} A${r - 2} ${r - 2} 0 0 1 ${x + 2} ${bot - r}Z" fill="${ICE}" stroke="#9cc9e6"/>
       <path d="M${x + 8} ${y + 12} l8 6 M${x + 20} ${y + 24} l6 -5 M${x + 10} ${y + 34} l9 3" stroke="#fff" stroke-width="2"/>`
    : `<path d="M${x + 2} ${y} H${x + w - 2} V${bot - r} A${r - 2} ${r - 2} 0 0 1 ${x + 2} ${bot - r}Z" fill="${WATER}"/>`;
  const lines = marks.map(([my, c]) => `<line x1="${x - 7}" x2="${x + w + 7}" y1="${my}" y2="${my}" stroke="${c}" stroke-width="2.5"/>`).join('');
  return `<path d="M${x} ${top} V${bot - r} A${r} ${r} 0 0 0 ${x + w} ${bot - r} V${top}" fill="#f4f8fb" stroke="${GLASS}" stroke-width="2"/>${liquid}
    <path d="M${x} ${top} V${bot - r} A${r} ${r} 0 0 0 ${x + w} ${bot - r} V${top}" fill="none" stroke="${GLASS}" stroke-width="2"/>
    <path d="M${x - 3} ${top - 14} H${x + w + 3} L${x + w} ${top + 4} H${x}Z" fill="#9b4d3a"/>${lines}`;
};
