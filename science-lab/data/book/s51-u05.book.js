// 세균 한 마리가 20분마다 둘로 나뉠 때(알맞은 조건의 예) 지난 시간에 따른 수
export const DOUBLING = { minutes: [0, 20, 40, 60, 80, 100, 120], count: [1, 2, 4, 8, 16, 32, 64] };
function doubling() {
  const W = 640, H = 360, L = 62, Rt = 610, T = 56, B = 300, n = DOUBLING.minutes.length, bw = 46, step = (Rt - L) / n, Y = (v) => B - (v / 70) * (B - T);
  const C = '#3346a0', INK = '#1f2a44', MUTED = '#5b6577', GRID = '#e3e7ef';
  const grid = [0, 20, 40, 60].map((v) => `<line x1="${L}" x2="${Rt}" y1="${Y(v)}" y2="${Y(v)}" stroke="${GRID}"/><text x="${L - 10}" y="${Y(v) + 5}" font-size="16" fill="${MUTED}" text-anchor="end">${v}</text>`).join('');
  const bars = DOUBLING.count.map((v, i) => { const x = L + step * i + (step - bw) / 2, y = Y(v);
    return `<rect x="${x}" y="${y}" width="${bw}" height="${B - y}" rx="4" fill="${C}"/><text x="${x + bw / 2}" y="${y - 8}" font-size="17" font-weight="800" fill="${INK}" text-anchor="middle">${v}</text>
      <text x="${x + bw / 2}" y="${B + 22}" font-size="16" fill="${MUTED}" text-anchor="middle">${DOUBLING.minutes[i]}</text>`; }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" role="img" aria-label="세균 한 마리가 20분마다 둘로 나뉘면 2시간 뒤 64마리가 되는 막대그래프" font-family="Pretendard, sans-serif">
    <rect width="${W}" height="${H}" rx="16" fill="#fff"/>${grid}<line x1="${L}" x2="${Rt}" y1="${B}" y2="${B}" stroke="#9aa3b2" stroke-width="1.4"/>${bars}
    <text x="16" y="26" font-size="17" font-weight="700" fill="${INK}">세균의 수(마리)</text>
    <text x="${(L + Rt) / 2}" y="${H - 12}" font-size="17" font-weight="700" fill="${INK}" text-anchor="middle">지난 시간(분)</text></svg>`;
}
