export function withGrade4StudyNotes(workbook){
 if(!Object.hasOwn(reviewed,workbook?.unit))return workbook;
 const patches=reviewed[workbook.unit],fields={};let changed=false;
 for(const key of ['pages','teacherStudentPages']){
  if(!Array.isArray(workbook[key]))continue;
  let pagesChanged=false;
  const pages=workbook[key].map(page=>{
   if(!Array.isArray(page.rail))return page;
   let railChanged=false;
   const rail=page.rail.map(note=>{
    if(note.title!=='내가 정리할 것'||!Object.hasOwn(patches,note.text))return note;
    railChanged=true;return {...note,text:patches[note.text]};
   });
   if(!railChanged)return page;
   pagesChanged=true;return {...page,rail};
  });
  if(pagesChanged){fields[key]=pages;changed=true;}
 }
 return changed?{...workbook,...fields}:workbook;
}
