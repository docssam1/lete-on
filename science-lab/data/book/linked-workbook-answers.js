const cache=new WeakMap();
const clone=value=>JSON.parse(JSON.stringify(value));
export function linkedWorkbookAnswers(rows,unit){
 if(!LINKED_WORKBOOK_ANSWER_UNITS.includes(unit)||!Array.isArray(rows))return rows;
 let changed=false;
 const next=rows.map(question=>{
  const patch=patches[question.id];
  if(!patch||patch.unit!==unit||question.status!=='authored'||JSON.stringify(question.sourceRef)!==JSON.stringify(patch.sourceRef)||question.sourceContent||question.contentVersion!==patch.previousVersion||question.prompt!==patch.prompt||question.workbookRef?.unit!==unit||question.workbookRef.id!==patch.workbookId||question.workbookRef.no!==patch.no||question.responseContract!=='written-explanation'||question.answerContract?.type!=='written-explanation'||question.answerContract.sample!==patch.previousSample)return question;
  if(patch.previousRequired&&JSON.stringify(question.answerContract.rubric?.required)!==JSON.stringify(patch.previousRequired))return question;
  changed=true;
  if(cache.has(question))return cache.get(question);
  const answerContract={...question.answerContract,sample:patch.sample};
  if(patch.required)answerContract.rubric={...question.answerContract.rubric,required:[...patch.required]};
  const current={...question,answerContract,contentVersion:LINKED_WORKBOOK_ANSWER_VERSION,previousVersions:[...(question.previousVersions?clone(question.previousVersions):[]),{...clone(question),version:question.contentVersion,snapshotKind:'full-question'}]};
  cache.set(question,current);return current;
 });
 return changed?next:rows;
}
export function withLinkedWorkbookAnswersClassroom(unit,mod){
 if(!mod?.classroomItems)return mod;
 const classroomItems=linkedWorkbookAnswers(mod.classroomItems,unit);
 return classroomItems===mod.classroomItems?mod:{...mod,classroomItems};
}
