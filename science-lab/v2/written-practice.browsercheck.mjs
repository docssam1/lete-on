// Local-only UI check; start a static server at SCIENCE_QA_URL (default localhost:18765).
// Set SCIENCE_PLAYWRIGHT to a Playwright module specifier and SCIENCE_CHROME if needed.
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { similar } from '../data/units/s41-u03.similar.js';
const { chromium } = await import(process.env.SCIENCE_PLAYWRIGHT || 'playwright');
const base = process.env.SCIENCE_QA_URL || 'http://127.0.0.1:18765/science-lab/v2/';
if (!['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('QA must run against a local server');
const output = await mkdtemp(join(tmpdir(), 'science-writing-qa-'));
const browser = await chromium.launch({ headless: true, ...(process.env.SCIENCE_CHROME ? { executablePath: process.env.SCIENCE_CHROME } : {}) });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [], missing = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('response', (r) => { if (r.status() >= 400 && r.url().startsWith(base.split('/science-lab/')[0])) missing.push(`${r.status()} ${r.url()}`); });
try {
  await page.goto(`${base}#/s41-u03/sub/E3`);
  const first = page.locator('[data-id="s41-u03-v006"]');
  await first.locator('.written-practice').waitFor();
  const expected = similar.find((it) => it.id === 's41-u03-v006');
  const beforeStorage = await page.evaluate(() => JSON.stringify(localStorage));
  assert.equal(await first.locator('.writing-sample').count(), 0);
  await first.getByRole('tab', { name: '채점 기준', exact: true }).click();
  assert.match(await first.locator('.writing-status').textContent(), /먼저 내 생각/);
  assert.equal(await first.locator('[data-writing-criterion]').count(), 0);
  await first.locator('summary').click();
  await first.getByRole('button', { name: '여러 생각', exact: true }).click();
  assert.match(await first.locator('.writing-guide-content').textContent(), /뜻이 같은 생각은 하나로/);
  const answer = '마그마가 땅 밖으로 나와 쌓여요.\n<img src=x onerror=alert(1)>';
  await first.locator('textarea').fill(answer);
  await first.getByRole('button', { name: '내 답과 비교하기' }).click();
  assert.equal(await first.locator('.writing-sample').textContent(), expected.answerContract.sample);
  assert.equal(await first.locator('[data-writing-panel="solution"] .writing-copy').textContent(), answer);
  assert.equal(await first.locator('.written-practice img').count(), 0);
  await first.getByRole('tab', { name: '채점 기준', exact: true }).click();
  const criteria = first.locator('[data-writing-criterion]');
  assert.equal(await criteria.count(), expected.answerContract.rubric.required.length);
  for (const c of await criteria.all()) await c.check();
  assert.match(await first.locator('.writing-check-count').textContent(), /선생님과도/);
  assert.equal(await first.getAttribute('data-done'), null);
  await first.getByRole('button', { name: '내 답 고쳐 쓰기' }).click();
  assert.equal(await first.locator('textarea').inputValue(), answer);
  await first.locator('textarea').fill('마그마가 땅 밖으로 분출하여 쌓인 지형이에요.');
  await first.getByRole('tab', { name: '채점 기준', exact: true }).click();
  assert.equal(await first.locator('[data-writing-criterion]:checked').count(), 0);
  await first.getByRole('tab', { name: '내 답', exact: true }).click();
  await first.getByRole('tab', { name: '내 답', exact: true }).press('End');
  assert.equal(await page.locator(':focus').getAttribute('data-writing-tab'), 'criteria');
  await page.keyboard.press('Enter');
  assert.equal(await first.getByRole('tab', { name: '채점 기준', exact: true }).getAttribute('aria-selected'), 'true');
  const paper = page.locator('[data-id="s41-u03-v050"]');
  await paper.locator('[data-writing-paper]').check();
  await paper.getByRole('tab', { name: '풀이', exact: true }).click();
  assert.match(await paper.locator('[data-writing-panel="solution"] .writing-copy').textContent(), /종이에 쓴 내 답/);
  assert.equal(await page.evaluate(() => JSON.stringify(localStorage)), beforeStorage);
  await first.screenshot({ path: join(output, 'desktop-criteria.png') });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await first.getByRole('tab', { name: '내 답', exact: true }).click();
    await first.locator('summary').evaluate((el) => { el.parentElement.open = true; });
    await first.screenshot({ path: join(output, `writing-${width}.png`) });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow in writing at ${width}`);
    await page.goto(`${base}#/s41-u03b/4`);
    await page.locator('.dsg .dsg-say').waitFor(); // 독쌤은 이제 화면 구석의 작은 말풍선
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow with teacher at ${width}`);
    await page.screenshot({ path: join(output, `teacher-${width}.png`) });
    await page.goto(`${base}#/s41-u03/sub/E3`);
    await first.locator('.written-practice').waitFor();
  }
  await page.setViewportSize({ width: 794, height: 1123 });
  await page.emulateMedia({ media: 'print' });
  await page.goto(`${base}#/s41-u03/print/student`);
  await page.locator('.book .ans-line').first().waitFor();
  assert.equal(await page.locator('.written-practice').count(), 0);
  assert.equal(await page.locator('.book .ans').count(), 0);
  await page.screenshot({ path: join(output, 'print-student.png') });
  await page.goto(`${base}#/s41-u03/print/teacher`);
  await page.locator('.book .ans').first().waitFor();
  assert.ok((await page.locator('.book .ans').count()) > 0);
  assert.equal(await page.locator('.written-practice').count(), 0);
  await page.screenshot({ path: join(output, 'print-teacher.png') });
  assert.deepEqual(errors, []);
  assert.deepEqual(missing, []);
  console.log(JSON.stringify({ status: 'passed', checks: ['answer gate', 'source sample preserved', 'escaped answer', 'criteria self-check', 'edit invalidation', 'paper path', 'keyboard tabs', 'no persistent answer/grade writes', '390/320px overflow', 'teacher bubble', 'student/teacher print separation', 'no page errors or missing local assets'], screenshots: output }, null, 2));
} finally { await browser.close(); }
