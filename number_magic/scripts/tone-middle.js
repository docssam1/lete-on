/* ko 문자열 리터럴만 바꾼다 — en·zh·tex·키 이름은 건드리지 않는다.
   따옴표 세 종류를 다 본다: 미분 단원은 본문에 f'(x) 가 들어가서 ko 문장이
   큰따옴표로 적혀 있다. 작은따옴표만 보면 M-44·M-45·M-60·M-62 가 통째로
   빠진다(실제로 1차 반영에서 11문장이 해요체로 남았고 check-tone.js 가 잡았다). */
const KO_LITERALS = [
  /(\bko\s*:\s*')((?:[^'\\\n]|\\.)*)(')/g,
  /(\bko\s*:\s*")((?:[^"\\\n]|\\.)*)(")/g,
  /(\bko\s*:\s*`)((?:[^`\\]|\\.)*)(`)/g,
];
function mapKoStrings(src, unknown, stat) {
  let out = src;
  for (const re of KO_LITERALS) {
    out = out.replace(re, (m, head, body, tail) => {
      const next = convert(body, unknown);
      if (next !== body) stat.n++;
      return head + next + tail;
    });
  }
  return out;
}

const targets = [];
