{
  const p = path.join(ROOT, 'data/threads.js');
  let src = fs.readFileSync(p, 'utf8');
  const ids = Object.keys(T).filter(k => T[k].unit && U[T[k].unit] && isMid(U[T[k].unit].tier));
  let n = 0;
  for (const id of ids) {
    const a = src.indexOf('\n' + id + ':{');
    if (a < 0) continue;
    const nxt = new RegExp('\\n[A-Z]{2,3}\\d+:\\{').exec(src.slice(a + 3));
    const b = nxt ? a + 3 + nxt.index + 1 : src.length;
    const stat = { n: 0 };
    const seg = mapKoStrings(src.slice(a + 1, b), unknown, stat);
    n += stat.n;
    src = src.slice(0, a + 1) + seg + src.slice(b);
  }
  if (n) { files++; total += n; if (WRITE) fs.writeFileSync(p, src); }
}

