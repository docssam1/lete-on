/* 받침으로 판정하는 두 규칙 — 표로 적기엔 가짓수가 너무 많고, 이 둘은 불규칙이 없다.
   ① 과거형: 받침 ㅆ + "어요"  → "습니다"  (들었어요→들었습니다, 그렸어요→그렸습니다)
   ② 받침(ㄹ 제외) + "아/어요" → "습니다"  (뒤집어요→뒤집습니다, 맞아요→맞습니다)
   ㄹ 받침을 빼는 이유: ㄹ 어간은 ㄹ이 떨어지며 "ㅂ니다"가 된다(늘다→늡니다).
   그런 낱말은 위 표에 따로 적었다. */
const JONG_SS = 20, JONG_R = 8;
function jong(ch) {
  const c = ch.charCodeAt(0) - 0xAC00;
  return (c < 0 || c > 11171) ? -1 : c % 28;
}

/* 문장 끝인가 — 마침표·느낌표·말줄임·줄표·여는괄호·문자열 끝이 오면 종결로 본다.
   **닫는 태그를 먼저 건너뛴다**: 콘텐츠는 "<b>커요</b> —" 처럼 강조가 종결 바로 뒤에
   붙는다. 이걸 빼먹으면 표에 멀쩡히 있는 낱말이 조용히 안 바뀐다(첫 판에서 실제로
   커요·만나요·같아요 등 열댓 개가 이 이유로 남았다).
   여는괄호도 종결로 본다 — "빼요(3+5=8)" 처럼 보충 설명이 붙는 문장이 흔하다.
   물음표(질문)·"세요"(권유)·"까요"(질문)는 표에 없거나 보고에서 제외된다. */
const TAIL = '(?=(?:<\\/[a-zA-Z][^>]*>)*\\s*(?:[.!…(]|—|$))';

function convert(s, unknown) {
  let out = s;
  /* 받침 규칙을 먼저 — 표의 짧은 항목(…나요·…려요)이 과거형을 잘못 집어가지 않게 한다 */
  out = out.replace(new RegExp('([가-힣])어요' + TAIL, 'g'),
    (m, c) => jong(c) === JONG_SS ? c + '습니다' : m);
  out = out.replace(new RegExp('([가-힣])([아어])요' + TAIL, 'g'),
    (m, c) => { const j = jong(c); return (j > 0 && j !== JONG_R) ? c + '습니다' : m; });
  for (const [from, to] of MAP) {
    out = out.replace(new RegExp(from + TAIL, 'g'), to);
  }
  /* 남은 "…요" 종결 보고 — 표에 없는 것은 바꾸지 않았다는 뜻 */
  const plain = out.replace(/<[^>]+>/g, '');
  for (const m of plain.matchAll(new RegExp('([가-힣]{1,6}요)' + TAIL, 'g'))) {
    /* 권유(…세요)와 질문(…할까요)은 의도적으로 둔다. 단 "…니까요"(이유)는 질문이
       아니라 평서문의 연결 종결이라 반드시 보고에 남겨야 한다. */
    if (/세요$/.test(m[1]) || (/까요$/.test(m[1]) && !/니까요$/.test(m[1]))) continue;
    unknown[m[1].slice(-4)] = (unknown[m[1].slice(-4)] || 0) + 1;
  }
  return out;
}

