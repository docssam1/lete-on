#!/usr/bin/env node
'use strict';
/* data/dunoro-review-candidates.json → data/dunoro-placement.js (browser copy).
 * Only app reference codes are copied; the private weekly transcript stays off Git.
 * --check: exit 1 when the browser copy is missing or out of date. */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const src = path.join(root, 'data/dunoro-review-candidates.json');
const out = path.join(root, 'data/dunoro-placement.js');
const data = JSON.parse(fs.readFileSync(src, 'utf8'));
const courses = data.courses.slice().sort((a, b) => a.course - b.course).map(row => ({
  course: row.course, level: row.level,
  previous: row.bands.previous.refs, current: row.bands.current.refs, next: row.bands.next.refs
}));
const body = JSON.stringify({ version: data.version, status: data.status, courses })
  .replace(/\{"course"/g, '\n  {"course"').replace(/\]\}$/, '\n]}');
const text = '/* Generated by scripts/build-dunoro-placement.js from data/dunoro-review-candidates.json.\n' +
  ' * Do not edit by hand: change the JSON, then run the script. */\n' +
  '(function () {\n  var W = typeof window !== \'undefined\' ? window : globalThis;\n' +
  '  W.NM_DUNORO_CANDIDATES = ' + body + ';\n})();\n';
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== text) {
    console.error('DUNORO_PLACEMENT_STALE: run node scripts/build-dunoro-placement.js');
    process.exit(1);
  }
  console.log('DUNORO_PLACEMENT_OK courses=' + courses.length);
} else {
  fs.writeFileSync(out, text);
  console.log('wrote data/dunoro-placement.js courses=' + courses.length);
}
