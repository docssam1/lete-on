/* 기존 문구/순서는 보존한다. 새 레벨은 threads.js에서 자동으로 가져오며,
   처음 등장한 스레드는 갈래를 명시해야 한다. */
var ADDITIONAL_THREADS = {
  decimal:['DC6'],
  middle1:['MD68','MD69','MD70','MD73','MD82','MD84','MD89'],
  middle2:['MD63','MD64','MD65','MD71','MD72','MD74','MD75','MD76','MD88'],
  middle3:['MD66','MD67','MD77','MD78','MD79','MD80','MD81','MD83','MD85','MD86','MD87','MD90']
};
function buildTopics(threads){
  if(!threads) throw new Error('drill-topics: threads.js must load first');
  var topics=CURATED_TOPICS.map(function(cat){
    return Object.assign({},cat,{subs:cat.subs.map(function(s){return Object.assign({},s);})});
  });
  var owners={};
  topics.forEach(function(cat){
    cat.subs.forEach(function(sub){
      if(owners[sub.thread] && owners[sub.thread]!==cat.id)
        throw new Error('drill-topics: duplicate category for '+sub.thread);
      owners[sub.thread]=cat.id;
    });
  });
  Object.keys(ADDITIONAL_THREADS).forEach(function(cat){
    ADDITIONAL_THREADS[cat].forEach(function(id){
      if(!threads[id]) throw new Error('drill-topics: unknown thread '+id);
      if(owners[id] && owners[id]!==cat) throw new Error('drill-topics: category conflict '+id);
      owners[id]=cat;
    });
  });
  Object.keys(threads).forEach(function(id){
    var th=threads[id],cat=topics.find(function(c){return c.id===owners[id];});
    if(!cat) throw new Error('drill-topics: choose a category for '+id);
    (th.levels||[]).forEach(function(lv){
      if(cat.subs.some(function(s){return s.thread===id && s.level===lv.id;})) return;
      var sub={thread:id,level:lv.id,label:th.name.ko,desc:lv.label.ko};
      var before=cat.subs.findIndex(function(s){return s.thread===id && s.level>lv.id;});
      if(before>=0){cat.subs.splice(before,0,sub);return;}
      var last=-1;
      cat.subs.forEach(function(s,i){if(s.thread===id)last=i;});
      cat.subs.splice(last<0?cat.subs.length:last+1,0,sub);
    });
  });
  return topics;
}
root.NM_BUILD_DRILL_TOPICS=buildTopics;
root.NM_DRILL_TOPICS=buildTopics(root.NM_THREADS);
