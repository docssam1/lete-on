export function attachOriginalSolutions(books) {
  const usedKeys = new Set();
  for (const book of books) {
    for (const lesson of book.lessons) {
      const key = `${book.id}/${lesson.id}`;
      const solutions = ORIGINAL_SOLUTIONS[key];
      if (!solutions) throw new Error(`${key}: original solution set missing`);
      if (solutions.length !== lesson.original.items.length) {
        throw new Error(`${key}: expected ${lesson.original.items.length} solutions, received ${solutions.length}`);
      }
      lesson.original.items.forEach((item, index) => {
        item.solution = solutions[index];
      });
      usedKeys.add(key);
    }
  }
  const unusedKeys = Object.keys(ORIGINAL_SOLUTIONS).filter((key) => !usedKeys.has(key));
  if (unusedKeys.length) throw new Error(`Unused original solution sets: ${unusedKeys.join(", ")}`);
}
