  if (value === "r") return halo(`<text x="${f(x)}" y="${f(y)}" text-anchor="middle" dominant-baseline="central" style="font-size:14px;font-style:italic;font-weight:600;fill:${INK};font-family:serif">r</text>`);
  const plain = text(f(x), f(y), value, { size: 12, weight: 600 });
