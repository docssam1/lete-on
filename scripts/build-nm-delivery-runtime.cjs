#!/usr/bin/env node
'use strict';
// Build the server's read-only assignment check from the exact browser sources.
// This script reads repository files only; it never loads credentials or a DB.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'..');
const OUTPUT='supabase/functions/weekly-notify/delivery-runtime.mjs';
const MODULES=['data/high-pacing.js','data/middle-extension.js','app/learning-plan.js','app/plan-control.js','app/delivery-plan.js'];
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');
function loadCourses(root=ROOT){
  const base=path.join(root,'number_magic'),box={console};box.window=box;vm.createContext(box);
  const html=fs.readFileSync(path.join(base,'index.html'),'utf8').replace(/<!--[\s\S]*?-->/g,'');
  const sources=[];let attached=false;
  for(const tag of html.matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["']/g)){
    const file=tag[1].split(/[?#]/)[0];if(!/^(engine\/|data\/)/.test(file))continue;
    if(file.includes('..')||!/^[-A-Za-z0-9_/.]+$/.test(file))throw Error('invalid_course_source');
    const text=fs.readFileSync(path.join(base,file),'utf8');sources.push({file,sha256:sha(text)});
    vm.runInContext(text,box,{filename:file,timeout:10000});
    if(file==='data/high-pacing.js'){attached=true;break;}
  }
  if(!attached||!box.NM_COURSES)throw Error('official_course_load_order_missing');
  return {courses:JSON.parse(JSON.stringify(box.NM_COURSES)),sources};
}
function courseMetadata(courses){
  const out={};
  for(const key of Object.keys(courses).filter(k=>/^C\d+$/.test(k)).sort((a,b)=>+a.slice(1)-+b.slice(1))){
    const c=courses[key];
    out[key]={tier:c.tier,order:c.order,sessions:c.sessions.map(s=>({
      ...(s.minutes!=null?{minutes:s.minutes}:{}),...(s.test!=null?{test:s.test}:{})
    })),...(c.studyPlan?{studyPlan:c.studyPlan}:{})};
  }
  return out;
}
function buildRuntime(root=ROOT){
  const {courses,sources}=loadCourses(root),metadata=JSON.stringify(courseMetadata(courses));
  const modules=MODULES.map(file=>({file,text:fs.readFileSync(path.join(root,'number_magic',file),'utf8')}));
  const provenance={courseSourceGraph:sha(JSON.stringify(sources)),courseMetadata:sha(metadata),modules:Object.fromEntries(modules.map(s=>[s.file,sha(s.text)]))};
  return `// Generated by scripts/build-nm-delivery-runtime.cjs. Do not edit.\n// Run the builder after changing a listed source; --check verifies exact bytes.\n// SHA-256 provenance: ${JSON.stringify(provenance)}\nconst scope=Object.create(null);\n(function(){\nconst window=scope;\n// Prevent CommonJS fallbacks even when a host exposes those globals.\nconst module=undefined,require=undefined;\n${modules.map(s=>`\n// BEGIN exact source: number_magic/${s.file}\n${s.text}\n// END exact source: number_magic/${s.file}\n`).join('')}\n})();\n// Metadata is assigned after module loading: preserve the original studyPlan,\n// without running attach() again against the reduced session metadata.\nscope.NM_COURSES=${metadata};\nexport function personalDeliveryState(config){\n  const plan=scope.NM_DELIVERY_PLAN.fromConfig(config);\n  if(!plan)return 'invalid';\n  const at=scope.NM_DELIVERY_PLAN.assignment(scope.NM_COURSES,plan,config.week);\n  if(!at||!Array.isArray(at.weekLessons))return 'invalid';\n  return at.weekLessons.length?'scheduled':'empty';\n}\n`;
}
function main(){
  const expected=buildRuntime(),file=path.join(ROOT,OUTPUT),check=process.argv.includes('--check');
  if(check){
    if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==expected){console.error('NM_DELIVERY_RUNTIME_STALE: run node scripts/build-nm-delivery-runtime.cjs');process.exitCode=1;return;}
    console.log('NM_DELIVERY_RUNTIME_CURRENT sha256='+sha(expected));return;
  }
  fs.writeFileSync(file,expected);console.log('NM_DELIVERY_RUNTIME_BUILT bytes='+Buffer.byteLength(expected)+' sha256='+sha(expected));
}
module.exports={OUTPUT,MODULES,loadCourses,courseMetadata,buildRuntime};
if(require.main===module)main();
